"""Checks for two-part questions. No API key needed.

Run from the project folder:  python test_question_parts.py

Part 1 checks which questions are split into a main part and a follow-up.
Part 2 runs the real Planner and Programmer with a scripted stand-in for
the language model and checks what each one is shown: the second part of
a question must never reach the prompt that plans or writes the query.

The exit code is 0 only when every check passes.
"""
from __future__ import annotations

import logging
import sys
from typing import Any, Callable, List, Optional, Tuple

from src.agents import planner, programmer
from src.question_parts import split_question

EXPENSES_QUESTION = (
    "For each service centre, show the total operating expenses for 2024, broken down by "
    "expense category. Also identify which location had the highest total expenses."
)
EXPENSES_MAIN = (
    "For each service centre, show the total operating expenses for 2024, broken down by "
    "expense category."
)
EXPENSES_FOLLOW_UP = "identify which location had the highest total expenses"
REWORDED = "Which location had the highest total expenses in 2024?"

# (label, question, expected main part or None for "not split", expected follow-up)
SPLIT_CASES: List[Tuple[str, str, Optional[str], str]] = [
    ("Breakdown, then 'Also identify which ... highest'",
     EXPENSES_QUESTION, EXPENSES_MAIN, EXPENSES_FOLLOW_UP),
    ("Two questions joined by 'Also,'",
     "What is the total revenue by region? Also, which service brought in the most revenue in 2025?",
     "What is the total revenue by region?", "which service brought in the most revenue in 2025"),
    ("'In addition, how many ...'",
     "Show revenue by region. In addition, how many employees does each region have?",
     "Show revenue by region.", "how many employees does each region have"),
    ("Scene-setting sentence stays with the main part",
     "Use 2024 data. Show revenue by location. Also identify which location had the highest expenses.",
     "Use 2024 data. Show revenue by location.", "identify which location had the highest expenses"),
    ("An adjustment is skipped, a later second question is split off",
     "Show revenue by location. Also include the city. Additionally, what was the overall total?",
     "Show revenue by location. Also include the city.", "what was the overall total"),
    ("Inside one sentence: ', and also identify which ...'",
     "Show expenses by category, and also identify which location had the highest total",
     "Show expenses by category", "identify which location had the highest total"),
    ("Second part on a new line",
     "Revenue by region\nplus which service is the top seller?",
     "Revenue by region", "which service is the top seller"),
    ("Not split: 'Rank the locations' is a sort order",
     "For all service centres in Bengaluru, Delhi, and Kolkata, calculate the total revenue "
     "generated by each location between January 1, 2024 and December 31, 2024. Rank the "
     "locations from highest to lowest revenue.", None, ""),
    ("Not split: operating surplus question",
     "Use 2024 data. Define operating surplus as total transaction revenue minus total recorded "
     "operating expenses. Calculate this separately for every location, rank the locations, and "
     "show revenue, expenses, and the resulting operating surplus.", None, ""),
    ("Not split: one-part question",
     "Which car-wash location is the most profitable?", None, ""),
    ("Not split: 'Also include the city' adds a column",
     "Show revenue by location. Also include the city.", None, ""),
    ("Not split: 'Also sort them' is a sort order",
     "Show revenue by location. Also sort them from highest to lowest.", None, ""),
    ("Not split: 'Also show the number of transactions' adds a column",
     "Show revenue by location. Also show the number of transactions.", None, ""),
    ("Not split: the first part is only scene-setting",
     "Use 2024 data. Also, which location earned the most?", None, ""),
    ("Not split: 'and also' joins two columns",
     "Show the top 5 services by revenue and also their highest price", None, ""),
    ("Not split: 'and also the highest expenses'",
     "Which location had the highest revenue and also the highest expenses?", None, ""),
    ("Not split: question that starts with 'Also'",
     "Also show revenue by region", None, ""),
    ("Not split: empty question", "", None, ""),
]


class _Reply:
    def __init__(self, content: str) -> None:
        self.content = content


class ScriptedModel:
    """Stands in for the language model: fixed replies, and a record of prompts."""

    def __init__(self, replies: List[Any]) -> None:
        self._replies = list(replies)
        self.prompts: List[str] = []

    def invoke(self, messages: List[Any]) -> _Reply:
        self.prompts.append("\n".join(str(message.content) for message in messages))
        reply = self._replies.pop(0)
        if isinstance(reply, Exception):
            raise reply
        return _Reply(reply)


def _use(model: ScriptedModel) -> None:
    planner.get_llm = lambda: model
    programmer.get_llm = lambda: model


def _state(question: str, **extra: Any) -> dict:
    return {"question": question, "schema_context": "TABLE expenses (id, location_id, amount)",
            "retry_count": 0, **extra}


def _also_asked_lines(plan: str) -> List[str]:
    return [line for line in plan.splitlines() if line.upper().startswith("ALSO ASKED:")]


def planner_plans_first_part_only() -> List[str]:
    model = ScriptedModel(["READ AS: Total expenses per location and category, 2024.\n"
                           "1. Tables: expenses, locations.\nALSO ASKED: something the model added",
                           REWORDED])
    _use(model)
    plan = planner.plan_query(_state(EXPENSES_QUESTION))["query_plan"]
    problems = []
    if len(model.prompts) != 2:
        problems.append(f"expected 2 model calls (plan, reword), saw {len(model.prompts)}")
    asked = model.prompts[0].split("USER QUESTION:")[-1]
    if EXPENSES_MAIN not in asked:
        problems.append("the planning prompt does not contain the first part")
    if "highest total expenses" in asked or "Also identify" in model.prompts[0]:
        problems.append("the planning prompt contains the second part")
    if EXPENSES_FOLLOW_UP not in model.prompts[1] or EXPENSES_QUESTION not in model.prompts[1]:
        problems.append("the rewording prompt lacks the second part or the full question")
    if _also_asked_lines(plan) != [f"ALSO ASKED: {REWORDED}"]:
        problems.append(f"ALSO ASKED lines are {_also_asked_lines(plan)}")
    if not plan.startswith("READ AS:"):
        problems.append("the plan lost its READ AS line")
    return problems


def planner_keeps_users_words_when_rewording_fails() -> List[str]:
    problems = []
    for label, bad_reply in (("a two-line reply", "Sure, here it is:\nWhich location?"),
                             ("a reply without a question mark", "The location with the highest expenses"),
                             ("an error from the model", RuntimeError("rate limit"))):
        model = ScriptedModel(["READ AS: x.\n1. Tables: expenses.", bad_reply])
        _use(model)
        plan = planner.plan_query(_state(EXPENSES_QUESTION))["query_plan"]
        if _also_asked_lines(plan) != [f"ALSO ASKED: {EXPENSES_FOLLOW_UP}"]:
            problems.append(f"after {label}: ALSO ASKED lines are {_also_asked_lines(plan)}")
    return problems


def planner_refusal_stays_one_line() -> List[str]:
    model = ScriptedModel(["UNANSWERABLE: There is no satisfaction data."])
    _use(model)
    question = "What is the average customer satisfaction score? Also, which location is the busiest?"
    plan = planner.plan_query(_state(question))["query_plan"]
    problems = []
    if plan != "UNANSWERABLE: There is no satisfaction data.":
        problems.append(f"the plan is {plan!r}")
    if len(model.prompts) != 1:
        problems.append(f"expected 1 model call, saw {len(model.prompts)}")
    return problems


def planner_leaves_one_part_questions_alone() -> List[str]:
    question = "Which car-wash location is the most profitable?"
    reply = "READ AS: Profit per location, all dates.\n1. Tables: transactions, expenses, locations."
    model = ScriptedModel([reply])
    _use(model)
    plan = planner.plan_query(_state(question))["query_plan"]
    problems = []
    if len(model.prompts) != 1:
        problems.append(f"expected 1 model call, saw {len(model.prompts)}")
    if question not in model.prompts[0].split("USER QUESTION:")[-1]:
        problems.append("the planning prompt does not contain the question")
    if plan != reply:
        problems.append("the plan was changed")
    return problems


def programmer_never_sees_second_part() -> List[str]:
    plan = f"READ AS: x.\n1. Tables: expenses, locations.\nALSO ASKED: {REWORDED}"
    problems = []
    for label, extra in (("first attempt", {}),
                         ("repair", {"error_message": "no such column", "sql_query": "SELECT 1;"})):
        model = ScriptedModel(["SELECT 1;"])
        _use(model)
        result = programmer.generate_sql(_state(EXPENSES_QUESTION, query_plan=plan, **extra))
        prompt = model.prompts[0]
        if "USER QUESTION:\n" + EXPENSES_MAIN + "\n" not in prompt:
            problems.append(f"{label}: the prompt does not contain the first part")
        if "highest total expenses" in prompt.lower():
            problems.append(f"{label}: the prompt contains the second part")
        if "1. Tables: expenses, locations." not in prompt:
            problems.append(f"{label}: the prompt lost the plan")
        if result["query_plan"] != plan:
            problems.append(f"{label}: the stored plan was changed")
        if result["sql_query"] != "SELECT 1;":
            problems.append(f"{label}: the SQL is {result['sql_query']!r}")
    return problems


WIRING_CHECKS: List[Tuple[str, Callable[[], List[str]]]] = [
    ("Planner plans the first part only, then attaches the reworded second part",
     planner_plans_first_part_only),
    ("Planner falls back to the user's own words when the rewording is unusable",
     planner_keeps_users_words_when_rewording_fails),
    ("Planner's refusal stays a single line, with no second model call",
     planner_refusal_stays_one_line),
    ("Planner leaves a one-part question untouched",
     planner_leaves_one_part_questions_alone),
    ("Programmer is never shown the second part, on a first attempt or a repair",
     programmer_never_sees_second_part),
]


def main() -> int:
    """Runs every check and prints a pass/fail summary.

    Returns:
        0 if all checks pass, otherwise 1.
    """
    logging.disable(logging.WARNING)
    passed = 0
    total = 0

    print("Which questions are split")
    for label, question, expected_main, expected_follow_up in SPLIT_CASES:
        total += 1
        main_part, follow_up = split_question(question)
        wanted = (expected_main if expected_main is not None else question.strip(), expected_follow_up)
        ok = (main_part, follow_up) == wanted
        passed += ok
        print(f"[{'PASS' if ok else 'FAIL'}] {label}")
        if follow_up:
            print(f"         held back: \"{follow_up}\"")
        if not ok:
            print(f"         expected: {wanted}")
            print(f"         got     : {(main_part, follow_up)}")

    print("\nWhat the Planner and Programmer are shown")
    for label, check in WIRING_CHECKS:
        total += 1
        try:
            problems = check()
        except Exception as exc:  # noqa: BLE001 - one broken check must not stop the rest
            problems = [f"{type(exc).__name__}: {exc}"]
        passed += not problems
        print(f"[{'PASS' if not problems else 'FAIL'}] {label}")
        for problem in problems:
            print(f"         {problem}")

    print(f"\n{passed}/{total} passed.")
    return 0 if passed == total else 1


if __name__ == "__main__":
    sys.exit(main())
